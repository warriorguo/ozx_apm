using System;
using System.Collections.Generic;
using OzxApm.Models;

namespace OzxApm.Network
{
    /// <summary>What ICountCheckpointSource.CollectCheckpoint found.</summary>
    internal enum CheckpointCollect
    {
        /// <summary>Nothing counted or closed since the last collection: the file stays as it is.</summary>
        Unchanged,
        /// <summary>A window is being closed and its events are not queued yet: ask again soon.</summary>
        Busy,
        /// <summary>The events now pending (possibly none: then the file is deleted).</summary>
        Collected
    }

    /// <summary>
    /// A collector whose counts wait in memory until its window closes
    /// (APM-24: exception repeat counts, custom events beyond the budget,
    /// custom metric series). The storage worker asks it, at most every
    /// ApmConfig.CountCheckpointIntervalSeconds and only after it reported a
    /// change (OfflineStorage.RequestCheckpoint), for the events its window
    /// would send now, and writes them to a checkpoint file. When the process
    /// dies before the window closes, the next launch uploads that file.
    ///
    /// Every pending count has a fixed event id (assigned when it starts) that
    /// its checkpoint copies and the window's final event share, so the server
    /// keeps one of them (APM-19 duplicate drop).
    /// </summary>
    internal interface ICountCheckpointSource
    {
        /// <summary>File name stem of its checkpoint ([A-Za-z0-9_]).</summary>
        string CheckpointName { get; }

        /// <summary>
        /// Called on the storage worker. Adds to into the events of the counts
        /// pending now (as the window would send them: with their fixed ids,
        /// without seq). Unchanged when nothing changed since the last call
        /// (unless force). Busy while a closed window's events are being handed
        /// to the queue (they would be in neither the file nor the queue).
        /// Must not block on the storage or log.
        /// </summary>
        CheckpointCollect CollectCheckpoint(List<BaseEvent> into, bool force);
    }

    /// <summary>
    /// 128-bit event ids for counts (APM-24), generated by the collector when a
    /// count starts so that its checkpoint copies and its final event carry the
    /// same one. Two SplitMix64 streams seeded once from a Guid (like the
    /// storage worker's ids): unique per install, no allocation. Not
    /// thread-safe: used under the collector's lock.
    /// </summary>
    internal sealed class EventIdSource
    {
        private ulong _s0, _s1;

        public EventIdSource()
        {
            var seed = Guid.NewGuid().ToByteArray();
            _s0 = BitConverter.ToUInt64(seed, 0);
            _s1 = BitConverter.ToUInt64(seed, 8);
        }

        public void Next(out ulong hi, out ulong lo)
        {
            do
            {
                hi = SplitMix64(ref _s0);
                lo = SplitMix64(ref _s1);
            } while ((hi | lo) == 0);
        }

        private static ulong SplitMix64(ref ulong state)
        {
            unchecked
            {
                ulong z = state += 0x9E3779B97F4A7C15UL;
                z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9UL;
                z = (z ^ (z >> 27)) * 0x94D049BB133111EBUL;
                return z ^ (z >> 31);
            }
        }
    }
}
